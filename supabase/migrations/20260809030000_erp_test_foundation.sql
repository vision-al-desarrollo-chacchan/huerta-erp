-- Base funcional para la versión integral de prueba (sin IA, proyectos ni servicios).
create table if not exists public.erp_clientes (
 id uuid primary key default gen_random_uuid(), empresa_id uuid not null references public.rest_empresas(id) on delete cascade,
 tipo_documento text not null default 'DNI', numero_documento text, nombre text not null, telefono text, email text,
 direccion text, activo boolean not null default true, created_at timestamptz not null default now(), unique(empresa_id,numero_documento)
);
create table if not exists public.erp_proveedores (
 id uuid primary key default gen_random_uuid(), empresa_id uuid not null references public.rest_empresas(id) on delete cascade,
 ruc text, razon_social text not null, contacto text, telefono text, email text, direccion text,
 condicion_pago text not null default 'Contado', activo boolean not null default true, created_at timestamptz not null default now(), unique(empresa_id,ruc)
);
create table if not exists public.erp_cotizaciones (
 id uuid primary key default gen_random_uuid(), empresa_id uuid not null references public.rest_empresas(id) on delete cascade,
 sucursal_id uuid not null references public.rest_sucursales(id) on delete restrict, numero bigint generated by default as identity,
 cliente_id uuid references public.erp_clientes(id) on delete set null, cliente_nombre text not null, estado text not null default 'borrador' check(estado in('borrador','enviada','aceptada','rechazada','vencida')),
 total numeric(12,2) not null default 0, vence_at date, observaciones text, creado_por uuid references auth.users(id), created_at timestamptz not null default now()
);
create table if not exists public.erp_cotizacion_items (
 id uuid primary key default gen_random_uuid(), cotizacion_id uuid not null references public.erp_cotizaciones(id) on delete cascade,
 producto_id uuid references public.rest_productos(id) on delete set null, descripcion text not null, cantidad numeric(12,3) not null check(cantidad>0), precio numeric(12,2) not null check(precio>=0)
);
create table if not exists public.erp_empleados (
 id uuid primary key default gen_random_uuid(), empresa_id uuid not null references public.rest_empresas(id) on delete cascade,
 dni text, nombres text not null, apellidos text not null, cargo text not null, area text not null, telefono text, email text,
 fecha_ingreso date not null default current_date, sueldo numeric(12,2) not null default 0, estado text not null default 'activo' check(estado in('activo','inactivo')), created_at timestamptz not null default now(), unique(empresa_id,dni)
);
create table if not exists public.erp_documentos (
 id uuid primary key default gen_random_uuid(), empresa_id uuid not null references public.rest_empresas(id) on delete cascade,
 nombre text not null, categoria text not null default 'Otros', descripcion text, url text, vence_at date,
 creado_por uuid references auth.users(id), created_at timestamptz not null default now()
);
create table if not exists public.erp_tareas (
 id uuid primary key default gen_random_uuid(), empresa_id uuid not null references public.rest_empresas(id) on delete cascade,
 titulo text not null, descripcion text, fecha date not null, hora time, prioridad text not null default 'media' check(prioridad in('baja','media','alta')),
 estado text not null default 'pendiente' check(estado in('pendiente','completada')), responsable text, created_at timestamptz not null default now()
);
create table if not exists public.erp_movimientos_contables (
 id uuid primary key default gen_random_uuid(), empresa_id uuid not null references public.rest_empresas(id) on delete cascade,
 fecha date not null default current_date, tipo text not null check(tipo in('ingreso','egreso')), categoria text not null,
 descripcion text not null, monto numeric(12,2) not null check(monto>0), metodo_pago text, referencia text,
 registrado_por uuid references auth.users(id), created_at timestamptz not null default now()
);
create table if not exists public.erp_configuracion (
 empresa_id uuid primary key references public.rest_empresas(id) on delete cascade, moneda text not null default 'PEN', igv numeric(5,2) not null default 18,
 serie_boleta text not null default 'B001', serie_factura text not null default 'F001', logo_url text, updated_at timestamptz not null default now()
);

