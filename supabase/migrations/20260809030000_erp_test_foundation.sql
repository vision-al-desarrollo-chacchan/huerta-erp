-- Administración de usuarios por invitación, sin exponer claves ni usar service_role en el navegador.
create table if not exists public.erp_invitaciones (
 id uuid primary key default gen_random_uuid(), empresa_id uuid not null references public.rest_empresas(id) on delete cascade,
 email text not null, rol text not null check(rol in('administrador','cajero','mozo','cocina')),
 token text not null unique default encode(gen_random_bytes(12),'hex'), estado text not null default 'pendiente' check(estado in('pendiente','usada','revocada')),
 creado_por uuid not null references auth.users(id), created_at timestamptz not null default now(), usada_at timestamptz
);
alter table public.erp_invitaciones enable row level security;

create or replace function public.rest_es_admin(target_empresa uuid) returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.rest_miembros where empresa_id=target_empresa and user_id=auth.uid() and activo and rol in('propietario','administrador'));
$$;
grant execute on function public.rest_es_admin(uuid) to authenticated;

drop policy if exists erp_invitaciones_admin on public.erp_invitaciones;
create policy erp_invitaciones_admin on public.erp_invitaciones for all to authenticated using(public.rest_es_admin(empresa_id)) with check(public.rest_es_admin(empresa_id));
drop policy if exists rest_empresas_admin_update on public.rest_empresas;
create policy rest_empresas_admin_update on public.rest_empresas for update to authenticated using(public.rest_es_admin(id)) with check(public.rest_es_admin(id));
drop policy if exists rest_miembros_admin_update on public.rest_miembros;
create policy rest_miembros_admin_update on public.rest_miembros for update to authenticated using(public.rest_es_admin(empresa_id)) with check(public.rest_es_admin(empresa_id));

create or replace function public.erp_crear_invitacion(p_empresa_id uuid,p_email text,p_rol text)
returns public.erp_invitaciones language plpgsql security invoker set search_path=public as $$
declare result public.erp_invitaciones;
begin
 if not public.rest_es_admin(p_empresa_id) then raise exception 'Solo el propietario o administrador puede invitar usuarios'; end if;
 if p_rol not in('administrador','cajero','mozo','cocina') then raise exception 'Rol inválido'; end if;
 insert into public.erp_invitaciones(empresa_id,email,rol,creado_por) values(p_empresa_id,lower(trim(p_email)),p_rol,auth.uid()) returning * into result;
 return result;
end; $$;
grant execute on function public.erp_crear_invitacion(uuid,text,text) to authenticated;

create or replace function public.erp_aceptar_invitacion(p_token text)
returns uuid language plpgsql security definer set search_path=public,auth as $$
declare inv public.erp_invitaciones; current_email text;
begin
 if auth.uid() is null then raise exception 'Debes iniciar sesión'; end if;
 select lower(email) into current_email from auth.users where id=auth.uid();
 select * into inv from public.erp_invitaciones where token=trim(p_token) and estado='pendiente' for update;
 if inv.id is null then raise exception 'Código de invitación inválido o ya utilizado'; end if;
 if lower(inv.email)<>current_email then raise exception 'La invitación pertenece a otro correo'; end if;
 insert into public.rest_miembros(empresa_id,user_id,rol,nombre,activo) values(inv.empresa_id,auth.uid(),inv.rol,split_part(current_email,'@',1),true)
 on conflict(empresa_id,user_id) do update set rol=excluded.rol,activo=true;
 update public.erp_invitaciones set estado='usada',usada_at=now() where id=inv.id;
 return inv.empresa_id;
end; $$;
grant execute on function public.erp_aceptar_invitacion(text) to authenticated;
